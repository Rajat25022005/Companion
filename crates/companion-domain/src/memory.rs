/// A discrete unit of stored memory across any hierarchical tier.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryItem {
    pub memory_id: MemoryId,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tenant_id: Option<TenantId>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub workspace_id: Option<WorkspaceId>,
    pub tier: MemoryTier,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub subject: Option<String>,
    pub content: String,
    #[serde(default)]
    pub metadata: serde_json::Value,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub embedding: Option<Vec<f32>>,
    pub importance: f32,
    pub confidence: f32,
    pub trust_class: TrustClass,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub valid_from: Option<DateTime<Utc>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub valid_to: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub last_accessed_at: DateTime<Utc>,
    pub access_count: u32,
    #[serde(default)]
    pub source_event_ids: Vec<EventId>,
    #[serde(default)]
    pub source_artifact_ids: Vec<ArtifactId>,
    #[serde(default)]
    pub supersedes: Vec<MemoryId>,
    pub status: MemoryStatus,
}

/// Alias for MemoryItem matching platform specification nomenclature.
pub type MemoryRecord = MemoryItem;

impl MemoryItem {
    pub fn new(tier: MemoryTier, content: impl Into<String>) -> Self {
        let now = Utc::now();
        Self {
            memory_id: MemoryId::new(),
            tenant_id: None,
            workspace_id: None,
            tier,
            subject: None,
            content: content.into(),
            metadata: serde_json::json!({}),
            embedding: None,
            importance: 1.0,
            confidence: 1.0,
            trust_class: TrustClass::AgentInferred,
            valid_from: Some(now),
            valid_to: None,
            created_at: now,
            updated_at: now,
            last_accessed_at: now,
            access_count: 0,
            source_event_ids: Vec::new(),
            source_artifact_ids: Vec::new(),
            supersedes: Vec::new(),
            status: MemoryStatus::Active,
        }
    }

    pub fn with_embedding(mut self, embedding: Vec<f32>) -> Self {
        self.embedding = Some(embedding);
        self
    }

    pub fn with_importance(mut self, importance: f32) -> Self {
        self.importance = importance.clamp(0.0, 5.0);
        self
    }

    pub fn with_confidence(mut self, confidence: f32) -> Self {
        self.confidence = confidence.clamp(0.0, 1.0);
        self
    }

    pub fn with_trust_class(mut self, trust_class: TrustClass) -> Self {
        self.trust_class = trust_class;
        self
    }

    pub fn with_subject(mut self, subject: impl Into<String>) -> Self {
        self.subject = Some(subject.into());
        self
    }

    pub fn with_tenant(mut self, tenant_id: TenantId) -> Self {
        self.tenant_id = Some(tenant_id);
        self
    }

    pub fn with_workspace(mut self, workspace_id: WorkspaceId) -> Self {
        self.workspace_id = Some(workspace_id);
        self
    }

    pub fn with_metadata(mut self, metadata: serde_json::Value) -> Self {
        self.metadata = metadata;
        self
    }

    pub fn with_validity(mut self, valid_from: Option<DateTime<Utc>>, valid_to: Option<DateTime<Utc>>) -> Self {
        self.valid_from = valid_from;
        self.valid_to = valid_to;
        self
    }

    pub fn with_provenance(mut self, event_ids: Vec<EventId>, artifact_ids: Vec<ArtifactId>) -> Self {
        self.source_event_ids = event_ids;
        self.source_artifact_ids = artifact_ids;
        self
    }

    /// Mark this item as accessed (touch for recency and decay calculation).
    pub fn touch(&mut self) {
        self.last_accessed_at = Utc::now();
        self.access_count += 1;
    }

    /// Check if this memory is currently active and temporally valid.
    pub fn is_valid_at(&self, time: DateTime<Utc>) -> bool {
        if self.status != MemoryStatus::Active {
            return false;
        }
        if let Some(vf) = self.valid_from {
            if time + chrono::Duration::seconds(5) < vf {
                return false;
            }
        }
        if let Some(vt) = self.valid_to {
            if time > vt {
                return false;
            }
        }
        true
    }

    /// Supersede this memory record with a newer replacement.
    pub fn supersede_with(&mut self, new_record_id: MemoryId) {
        self.status = MemoryStatus::Superseded;
        self.updated_at = Utc::now();
        self.valid_to = Some(self.updated_at);
        if !self.supersedes.contains(&new_record_id) {
            self.supersedes.push(new_record_id);
        }
    }

    /// Calculate recency decay factor (1.0 for new/recent, approaching 0.0 over time).
    /// Uses exponential decay with a configurable half-life (default 30 days).
    pub fn recency_decay(&self, now: DateTime<Utc>, half_life_days: f32) -> f32 {
        let age_seconds = (now - self.last_accessed_at).num_seconds().max(0) as f32;
        let half_life_seconds = half_life_days * 86400.0;
        (-0.693147 * (age_seconds / half_life_seconds)).exp()
    }
}

