/// Trust and authority classification of a memory item.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum TrustClass {
    /// Imported from potentially hostile or unverified external content.
    ExternalUntrusted,
    /// Generated by model inference / reasoning.
    #[default]
    AgentInferred,
    /// Extracted from an authorized project document or artifact.
    DocumentDerived,
    /// Directly confirmed by deterministic tool / verifier evidence.
    ToolVerified,
    /// Explicitly stated or confirmed by the human user.
    UserConfirmed,
}

impl TrustClass {
    /// Multiplicative trust weight used in multi-factor scoring (0.0 to 1.0).
    pub fn trust_weight(&self) -> f32 {
        match self {
            Self::UserConfirmed => 1.0,
            Self::ToolVerified => 0.9,
            Self::DocumentDerived => 0.7,
            Self::AgentInferred => 0.5,
            Self::ExternalUntrusted => 0.2,
        }
    }

    /// Numerical ranking for precedence during contradiction resolution (higher wins).
    pub fn authority_rank(&self) -> u8 {
        match self {
            Self::ExternalUntrusted => 1,
            Self::AgentInferred => 2,
            Self::DocumentDerived => 3,
            Self::ToolVerified => 4,
            Self::UserConfirmed => 5,
        }
    }
}

/// Lifecycle status of a memory record.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum MemoryStatus {
    /// Active and available for retrieval.
    #[default]
    Active,
    /// Deprecated due to age or reduced relevance.
    Deprecated,
    /// Explicitly revoked or forgotten by policy / user command.
    Revoked,
    /// Replaced by a newer, higher-authority memory item.
    Superseded,
}

