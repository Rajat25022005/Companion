/// A named entity in the knowledge graph.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Entity {
    pub entity_id: EntityId,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tenant_id: Option<TenantId>,
    pub name: String,
    pub entity_type: String,
    #[serde(default)]
    pub attributes: HashMap<String, serde_json::Value>,
    pub confidence: f32,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
}

impl Entity {
    pub fn new(name: impl Into<String>, entity_type: impl Into<String>) -> Self {
        let now = Utc::now();
        Self {
            entity_id: EntityId::new(),
            tenant_id: None,
            name: name.into(),
            entity_type: entity_type.into(),
            attributes: HashMap::new(),
            confidence: 1.0,
            created_at: now,
            updated_at: now,
        }
    }

    pub fn with_attribute(mut self, key: impl Into<String>, value: serde_json::Value) -> Self {
        self.attributes.insert(key.into(), value);
        self.updated_at = Utc::now();
        self
    }
}

/// A semantic relationship triple: (subject) -[predicate]-> (object).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RelationshipTriple {
    pub relationship_id: RelationshipId,
    pub subject: String,
    pub predicate: String,
    pub object: String,
    pub weight: f32,
    pub confidence: f32,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub valid_from: Option<DateTime<Utc>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub valid_to: Option<DateTime<Utc>>,
    pub created_at: DateTime<Utc>,
}

impl RelationshipTriple {
    pub fn new(subject: impl Into<String>, predicate: impl Into<String>, object: impl Into<String>) -> Self {
        let now = Utc::now();
        Self {
            relationship_id: RelationshipId::new(),
            subject: subject.into(),
            predicate: predicate.into(),
            object: object.into(),
            weight: 1.0,
            confidence: 1.0,
            valid_from: Some(now),
            valid_to: None,
            created_at: now,
        }
    }

    pub fn with_weight(mut self, weight: f32) -> Self {
        self.weight = weight;
        self
    }

    pub fn with_confidence(mut self, confidence: f32) -> Self {
        self.confidence = confidence;
        self
    }

    pub fn is_valid_at(&self, time: DateTime<Utc>) -> bool {
        if let Some(vf) = self.valid_from {
            if time + chrono::Duration::seconds(5) < vf {
                return false;
            }
        }
        if let Some(vt) = self.valid_to {
            if time > vt {
                return false;
            }
        }
        true
    }
}

