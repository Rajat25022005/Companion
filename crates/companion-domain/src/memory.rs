/// The 7 functional storage tiers of the hierarchical memory subsystem.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MemoryTier {
    /// L0 Hot: Active turn reasoning scratchpad and working state.
    Working,
    /// L1 Warm: Conversation turn history buffer and session transcripts.
    Session,
    /// L2 Warm: Past task trajectories, event summaries, and retrospectives.
    Episodic,
    /// L3 Cold: Long-term semantic knowledge chunks and vector embeddings.
    Semantic,
    /// L4 Cold: Knowledge graph entity-relationship triples.
    Relational,
    /// L5 Cold: Versioned procedural capabilities and successful workflows.
    Procedural,
    /// L6 Cold: Durable external work product references and evidence.
    Artifacts,
}

impl MemoryTier {
    /// Numerical level in the hierarchy (0 to 6).
    pub fn level(&self) -> u8 {
        match self {
            Self::Working => 0,
            Self::Session => 1,
            Self::Episodic => 2,
            Self::Semantic => 3,
            Self::Relational => 4,
            Self::Procedural => 5,
            Self::Artifacts => 6,
        }
    }
}

impl std::fmt::Display for MemoryTier {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Working => write!(f, "L0:working"),
            Self::Session => write!(f, "L1:session"),
            Self::Episodic => write!(f, "L2:episodic"),
            Self::Semantic => write!(f, "L3:semantic"),
            Self::Relational => write!(f, "L4:relational"),
            Self::Procedural => write!(f, "L5:procedural"),
            Self::Artifacts => write!(f, "L6:artifacts"),
        }
    }
}

